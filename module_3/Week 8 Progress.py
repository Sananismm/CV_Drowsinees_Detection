qualified_events = []
start = None

for i in range(len(active) + 1):
    is_open = active[i] if i < len(active) else False

    if is_open and start is None:
        start = i

    elif not is_open and start is not None:
        end = i - 1
        duration = (end - start + 1) / fps
        peak = np.nanmax(mar[start:end + 1])

        if duration >= YAWN_DURATION_SECONDS and peak >= START_THRESHOLD:
            qualified_events.append((start, end))

        start = None

print("Qualified yawn events:", len(qualified_events))

for n, (s, e) in enumerate(qualified_events, 1):
    print(f"Yawn {n}: {times[s]:.2f}s to {times[e]:.2f}s")

